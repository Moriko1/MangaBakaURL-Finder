import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

function formatBuildDate(date) {
  const year = date.getFullYear();
  const month = String(date.getMonth() + 1).padStart(2, "0");
  const day = String(date.getDate()).padStart(2, "0");
  return `${year}-${month}-${day}`;
}

const buildDate = formatBuildDate(new Date());
const outputPath = resolve(process.cwd(), "src", "build-info.ts");
const content = `// Generated by scripts/update-build-info.mjs
(globalThis as typeof globalThis & { BUILD_DATE?: string }).BUILD_DATE = "${buildDate}";
`;

writeFileSync(outputPath, content, "utf8");
